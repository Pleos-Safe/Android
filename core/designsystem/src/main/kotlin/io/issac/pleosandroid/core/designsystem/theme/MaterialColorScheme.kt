    primary = actionPrimary,
    onPrimary = textOnAction,
    primaryContainer = chipSelected,
    onPrimaryContainer = actionPrimary,
    inversePrimary = background,
    secondary = actionSecondary,
    onSecondary = textPrimary,
    secondaryContainer = actionSecondary,
    onSecondaryContainer = textPrimary,
    tertiary = surface,
    onTertiary = textPrimary,
    tertiaryContainer = surface,
    onTertiaryContainer = textPrimary,
    background = background,
    onBackground = textPrimary,
    surface = surface,
    onSurface = textPrimary,
    surfaceVariant = surface,
    onSurfaceVariant = textSecondary,
    surfaceTint = surface,
    inverseSurface = textPrimary,
    inverseOnSurface = background,
    error = actionDanger,
    onError = textOnAction,
    errorContainer = surface,
    onErrorContainer = statusAttention,
    outline = borderDefault,
    outlineVariant = borderControl,
    scrim = background,
    surfaceBright = surface,
    surfaceDim = background,
    surfaceContainer = surface,
    surfaceContainerHigh = surface,
    surfaceContainerHighest = surface,
    surfaceContainerLow = surface,
    surfaceContainerLowest = background,
    primaryFixed = actionPrimary,
    primaryFixedDim = actionPrimary,
    onPrimaryFixed = textOnAction,
    onPrimaryFixedVariant = textOnAction,
    secondaryFixed = actionSecondary,
    secondaryFixedDim = actionSecondary,
    onSecondaryFixed = textPrimary,
    onSecondaryFixedVariant = textSecondary,
    tertiaryFixed = surface,
    tertiaryFixedDim = surface,
    onTertiaryFixed = textPrimary,
    onTertiaryFixedVariant = textSecondary,
)
